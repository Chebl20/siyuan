CREATE SCHEMA IF NOT EXISTS siyuan;
SET search_path TO siyuan;

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS stat (
	key TEXT PRIMARY KEY,
	value TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS blocks (
	id TEXT PRIMARY KEY,
	parent_id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	hash TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	hpath TEXT NOT NULL DEFAULT '',
	name TEXT NOT NULL DEFAULT '',
	alias TEXT NOT NULL DEFAULT '',
	memo TEXT NOT NULL DEFAULT '',
	tag TEXT NOT NULL DEFAULT '',
	content TEXT NOT NULL DEFAULT '',
	fcontent TEXT NOT NULL DEFAULT '',
	markdown TEXT NOT NULL DEFAULT '',
	length BIGINT NOT NULL DEFAULT 0,
	type TEXT NOT NULL DEFAULT '',
	subtype TEXT NOT NULL DEFAULT '',
	ial TEXT NOT NULL DEFAULT '',
	sort BIGINT NOT NULL DEFAULT 0,
	created TEXT NOT NULL DEFAULT '',
	updated TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS block_search (
	id TEXT PRIMARY KEY,
	search_vector tsvector
);

CREATE TABLE IF NOT EXISTS spans (
	id TEXT PRIMARY KEY,
	block_id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	content TEXT NOT NULL DEFAULT '',
	markdown TEXT NOT NULL DEFAULT '',
	type TEXT NOT NULL DEFAULT '',
	ial TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS assets (
	id TEXT PRIMARY KEY,
	block_id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	docpath TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	name TEXT NOT NULL DEFAULT '',
	title TEXT NOT NULL DEFAULT '',
	hash TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS attributes (
	id TEXT PRIMARY KEY,
	name TEXT NOT NULL DEFAULT '',
	value TEXT NOT NULL DEFAULT '',
	type TEXT NOT NULL DEFAULT '',
	block_id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS refs (
	id TEXT PRIMARY KEY,
	def_block_id TEXT NOT NULL DEFAULT '',
	def_block_parent_id TEXT NOT NULL DEFAULT '',
	def_block_root_id TEXT NOT NULL DEFAULT '',
	def_block_path TEXT NOT NULL DEFAULT '',
	block_id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	content TEXT NOT NULL DEFAULT '',
	markdown TEXT NOT NULL DEFAULT '',
	type TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS file_annotation_refs (
	id TEXT PRIMARY KEY,
	file_path TEXT NOT NULL DEFAULT '',
	annotation_id TEXT NOT NULL DEFAULT '',
	block_id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	content TEXT NOT NULL DEFAULT '',
	type TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS block_embeddings (
	id TEXT PRIMARY KEY,
	root_id TEXT NOT NULL DEFAULT '',
	box TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	embedding BYTEA,
	model TEXT NOT NULL DEFAULT '',
	content_len INTEGER NOT NULL DEFAULT 0,
	updated TEXT NOT NULL DEFAULT '',
	fail_count INTEGER NOT NULL DEFAULT 0,
	last_tried INTEGER NOT NULL DEFAULT 0,
	ignored_type INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS blocktrees_row (
	rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id TEXT NOT NULL DEFAULT '',
	root_id TEXT NOT NULL DEFAULT '',
	parent_id TEXT NOT NULL DEFAULT '',
	box_id TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	hpath TEXT NOT NULL DEFAULT '',
	updated TEXT NOT NULL DEFAULT '',
	type TEXT NOT NULL DEFAULT '',
	UNIQUE (id)
);

CREATE OR REPLACE VIEW blocktrees AS
	SELECT id, root_id, parent_id, box_id, path, hpath, updated, type
	FROM blocktrees_row;

CREATE TABLE IF NOT EXISTS histories (
	id TEXT NOT NULL DEFAULT '',
	type INTEGER NOT NULL DEFAULT 0,
	op TEXT NOT NULL DEFAULT '',
	title TEXT NOT NULL DEFAULT '',
	content TEXT NOT NULL DEFAULT '',
	path TEXT NOT NULL DEFAULT '',
	created TEXT NOT NULL DEFAULT '',
	PRIMARY KEY (path, created, op)
);

CREATE OR REPLACE VIEW histories_fts_case_insensitive AS
	SELECT id, type, op, title, content, path, created
	FROM histories;

CREATE TABLE IF NOT EXISTS history_search (
	path TEXT NOT NULL DEFAULT '',
	created TEXT NOT NULL DEFAULT '',
	op TEXT NOT NULL DEFAULT '',
	search_vector tsvector,
	PRIMARY KEY (path, created, op)
);

CREATE TABLE IF NOT EXISTS asset_contents (
	id TEXT NOT NULL DEFAULT '',
	name TEXT NOT NULL DEFAULT '',
	ext TEXT NOT NULL DEFAULT '',
	path TEXT PRIMARY KEY,
	size BIGINT NOT NULL DEFAULT 0,
	updated BIGINT NOT NULL DEFAULT 0,
	content TEXT NOT NULL DEFAULT ''
);

CREATE OR REPLACE VIEW asset_contents_fts_case_insensitive AS
	SELECT id, name, ext, path, size, updated, content
	FROM asset_contents;

CREATE TABLE IF NOT EXISTS asset_content_search (
	path TEXT PRIMARY KEY,
	search_vector tsvector
);

CREATE INDEX IF NOT EXISTS idx_blocks_parent_id ON blocks(parent_id);
