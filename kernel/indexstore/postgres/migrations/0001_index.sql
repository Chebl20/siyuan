CREATE INDEX IF NOT EXISTS idx_attributes_block_id ON attributes(block_id);
CREATE INDEX IF NOT EXISTS idx_attributes_root_id ON attributes(root_id);
CREATE INDEX IF NOT EXISTS idx_refs_def_block_id ON refs(def_block_id);
CREATE INDEX IF NOT EXISTS idx_refs_def_block_root_id ON refs(def_block_root_id);
CREATE INDEX IF NOT EXISTS idx_block_embeddings_root_id ON block_embeddings(root_id);
CREATE INDEX IF NOT EXISTS idx_blocktrees_root_id ON blocktrees_row(root_id);
CREATE INDEX IF NOT EXISTS idx_blocktrees_box_id ON blocktrees_row(box_id);
CREATE INDEX IF NOT EXISTS idx_blocktrees_doc_path ON blocktrees_row(box_id, path) WHERE type = 'd';
CREATE INDEX IF NOT EXISTS idx_blocktrees_root_box ON blocktrees_row(root_id, box_id);
CREATE INDEX IF NOT EXISTS idx_block_search_vector ON block_search USING GIN (search_vector);
CREATE INDEX IF NOT EXISTS idx_blocks_content_trgm ON blocks USING GIN (content gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_blocks_name_trgm ON blocks USING GIN (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_history_search_vector ON history_search USING GIN (search_vector);
CREATE INDEX IF NOT EXISTS idx_asset_content_search_vector ON asset_content_search USING GIN (search_vector);

CREATE OR REPLACE FUNCTION delete_block_search() RETURNS trigger AS $$
BEGIN
	DELETE FROM block_search WHERE id = OLD.id;
	RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS blocks_delete_search ON blocks;
CREATE TRIGGER blocks_delete_search
	AFTER DELETE ON blocks
	FOR EACH ROW EXECUTE FUNCTION delete_block_search();

CREATE OR REPLACE FUNCTION delete_history_search() RETURNS trigger AS $$
BEGIN
	DELETE FROM history_search WHERE path = OLD.path AND created = OLD.created AND op = OLD.op;
	RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS histories_delete_search ON histories;
CREATE TRIGGER histories_delete_search
	AFTER DELETE ON histories
	FOR EACH ROW EXECUTE FUNCTION delete_history_search();

CREATE OR REPLACE FUNCTION delete_asset_content_search() RETURNS trigger AS $$
BEGIN
	DELETE FROM asset_content_search WHERE path = OLD.path;
	RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS asset_contents_delete_search ON asset_contents;
CREATE TRIGGER asset_contents_delete_search
	AFTER DELETE ON asset_contents
	FOR EACH ROW EXECUTE FUNCTION delete_asset_content_search();
